-- 4.3 Cascading LOV Query (Department -> Employees)
-- Parent: P3_DEPT_ID, Child: P3_MANAGER_ID
SELECT emp_name AS display_value, emp_id AS return_value
FROM apex_employees
WHERE dept_id = :P3_DEPT_ID
  AND is_active = 1
ORDER BY emp_name;

-- 4.4 Tree Region Query (Organization Hierarchy)
SELECT 
    CASE WHEN CONNECT_BY_ISLEAF = 1 THEN 0 ELSE 1 END AS is_parent,
    LEVEL AS level,
    emp_id AS value,
    emp_name AS title,
    job_title AS tooltip,
    NULL AS link,
    'fa-user' AS icon
FROM apex_employees
WHERE is_active = 1
START WITH manager_id IS NULL
CONNECT BY PRIOR emp_id = manager_id
ORDER SIBLINGS BY emp_name;

