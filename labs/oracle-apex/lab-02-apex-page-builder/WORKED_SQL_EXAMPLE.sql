-- -----------------------------------------------------------------------------
-- SECTION 7: Page Performance Monitoring Queries
-- -----------------------------------------------------------------------------

-- 7.1 Page View Statistics
SELECT 
    p.page_number,
    p.page_name,
    COUNT(l.log_id) AS view_count,
    AVG(l.elapsed_time) AS avg_load_time_ms,
    MAX(l.elapsed_time) AS max_load_time_ms,
    COUNT(DISTINCT l.user_id) AS unique_users
FROM apex_pages p
LEFT JOIN apex_activity_log l ON p.page_id = l.page_id
    AND l.timestamp >= SYSDATE - 30
GROUP BY p.page_number, p.page_name
ORDER BY view_count DESC;

-- 7.2 Slow Region Queries
SELECT 
    r.region_name,
    p.page_name,
    AVG(l.elapsed_time) AS avg_time_ms,
    l.query_text
FROM apex_regions r
JOIN apex_pages p ON r.page_id = p.page_id
JOIN apex_region_perf_log l ON r.region_id = l.region_id
WHERE l.timestamp >= SYSDATE - 7
  AND l.elapsed_time > 1000
ORDER BY avg_time_ms DESC;

