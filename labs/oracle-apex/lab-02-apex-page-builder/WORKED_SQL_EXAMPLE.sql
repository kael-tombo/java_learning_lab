-- SECTION 8: Migration & Deployment Scripts
-- -----------------------------------------------------------------------------

-- 8.1 Export Page Definition (for version control)
SELECT 
    'PAGE ' || p.page_number || ': ' || p.page_name AS definition,
    r.region_name || ' (' || r.region_type || ')' AS region,
    pi.item_name || ' [' || pi.item_type || ']' AS item
FROM apex_pages p
LEFT JOIN apex_regions r ON p.page_id = r.page_id
LEFT JOIN apex_page_items pi ON p.page_id = pi.page_id
WHERE p.app_id = 100
ORDER BY p.page_number, r.display_sequence, pi.display_sequence;

-- 8.2 Page Component Dependency Check
SELECT 
    'Item ' || pi.item_name || ' referenced by DA ' || da.da_name AS dependency
FROM apex_page_items pi
JOIN apex_dynamic_actions da ON pi.page_id = da.page_id
JOIN apex_da_actions daa ON da.da_id = daa.da_id
WHERE (daa.affected_elements = pi.item_name 
    OR daa.plsql_code LIKE '%' || pi.item_name || '%'
    OR daa.javascript_code LIKE '%' || pi.item_name || '%')
  AND pi.page_id = 3;

