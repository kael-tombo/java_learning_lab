-- 4.1 Dynamic Report Columns (PIVOT for matrix reports)
-- Department x Job Title salary matrix
SELECT * FROM (
    SELECT d.dept_name, e.job_title, e.salary
    FROM v_employee_directory e
    JOIN apex_departments d ON e.dept_id = d.dept_id
)
PIVOT (
    AVG(salary) AS avg_sal, COUNT(*) AS cnt
    FOR job_title IN (
        'Senior Developer' AS sr_dev,
        'Developer' AS dev,
        'DevOps Engineer' AS devops,
        'Sales Lead' AS sales_lead,
        'Sales Rep' AS sales_rep,
        'Marketing Manager' AS mkt_mgr,
        'Content Specialist' AS content,
        'HR Director' AS hr_dir,
        'HR Specialist' AS hr_spec,
        'Finance Manager' AS fin_mgr
    )
)
ORDER BY dept_name;

