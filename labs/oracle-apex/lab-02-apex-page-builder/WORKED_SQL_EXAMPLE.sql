-- 3.1 Employee Directory View (used by Interactive Report)
CREATE OR REPLACE VIEW v_employee_directory AS
SELECT 
    e.emp_id,
    e.emp_name,
    e.emp_email,
    e.job_title,
    e.hire_date,
    e.salary,
    e.is_active,
    d.dept_id,
    d.dept_name,
    d.dept_location,
    m.emp_name AS manager_name
FROM apex_employees e
JOIN apex_departments d ON e.dept_id = d.dept_id
LEFT JOIN apex_employees m ON e.manager_id = m.emp_id
WHERE e.is_active = 1;

-- 3.2 Page Metadata View (for dynamic page listing)
CREATE OR REPLACE VIEW v_page_metadata AS
SELECT 
    p.page_id,
    p.app_id,
    p.page_number,
    p.page_name,
    p.page_mode,
    COUNT(r.region_id) AS region_count,
    MAX(p.updated_at) AS last_modified
FROM apex_pages p
LEFT JOIN apex_regions r ON p.page_id = r.page_id AND r.is_visible = 1
GROUP BY p.page_id, p.app_id, p.page_number, p.page_name, p.page_mode;

