CREATE TABLE apex_pages (
    page_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id           NUMBER NOT NULL,
    page_number      NUMBER NOT NULL,
    page_name        VARCHAR2(255) NOT NULL,
    page_mode        VARCHAR2(20) DEFAULT 'Normal' CHECK (page_mode IN ('Normal', 'Modal Dialog', 'Non-Modal Dialog')),
    page_template    VARCHAR2(100),
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (app_id, page_number)
);

CREATE TABLE apex_regions (
    region_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id          NUMBER NOT NULL REFERENCES apex_pages(page_id),
    region_name      VARCHAR2(255) NOT NULL,
    region_type      VARCHAR2(50) NOT NULL CHECK (region_type IN 
        ('Interactive Report', 'Classic Report', 'Form', 'Chart', 'Calendar', 'Tree', 'Static Content', 'PL/SQL Dynamic Content')),
    source_type      VARCHAR2(50),
    source_query     CLOB,
    display_sequence NUMBER DEFAULT 10,
    region_template  VARCHAR2(100),
    parent_region_id NUMBER REFERENCES apex_regions(region_id),
    is_visible       NUMBER(1) DEFAULT 1 CHECK (is_visible IN (0,1))
);

CREATE TABLE apex_page_items (
    item_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id          NUMBER NOT NULL REFERENCES apex_pages(page_id),
    region_id        NUMBER REFERENCES apex_regions(region_id),
    item_name        VARCHAR2(255) NOT NULL,
    item_label       VARCHAR2(255),
    item_type        VARCHAR2(50) NOT NULL CHECK (item_type IN 
        ('Text Field', 'Text Area', 'Select List', 'Checkbox', 'Radio Group', 'Date Picker', 
         'Hidden', 'Display Only', 'File Browse', 'Popup LOV', 'Shuttle', 'Switch')),
    lov_query        CLOB,
    lov_display_extra NUMBER(1) DEFAULT 1,
    source_type      VARCHAR2(50),
    source_value     CLOB,
    is_required      NUMBER(1) DEFAULT 0 CHECK (is_required IN (0,1)),
    validation_regex VARCHAR2(4000),
    display_sequence NUMBER DEFAULT 10
);

CREATE TABLE apex_dynamic_actions (
    da_id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id          NUMBER NOT NULL REFERENCES apex_pages(page_id),
    da_name          VARCHAR2(255) NOT NULL,
    event_type       VARCHAR2(50) NOT NULL,
    selection_type   VARCHAR2(50) NOT NULL,
    selection_value  VARCHAR2(255),
    condition_type   VARCHAR2(50),
    condition_expr1  VARCHAR2(4000),
    condition_expr2  VARCHAR2(4000),
    da_sequence      NUMBER DEFAULT 10
);

CREATE TABLE apex_da_actions (
    action_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    da_id            NUMBER NOT NULL REFERENCES apex_dynamic_actions(da_id),
    action_type      VARCHAR2(50) NOT NULL,
    affected_elements_type VARCHAR2(50),
    affected_elements VARCHAR2(255),
    plsql_code       CLOB,
    javascript_code  CLOB,
    action_sequence  NUMBER DEFAULT 10
);

