-- SECTION 4: Pattern Matching (MATCH_RECOGNIZE) for Business Events
-- -----------------------------------------------------------------------------

-- 4.1 Detect Customer Purchase Patterns (3+ orders in 30 days)
SELECT *
FROM (
    SELECT 
        c.customer_name,
        so.order_date,
        so.total_amount,
        ROW_NUMBER() OVER (PARTITION BY c.customer_id ORDER BY so.order_date) AS rn
    FROM sales_orders so
    JOIN customers c ON so.customer_id = c.customer_id
    WHERE so.status IN ('Shipped', 'Delivered')
)
MATCH_RECOGNIZE (
    PARTITION BY customer_name
    ORDER BY order_date
    MEASURES
        COUNT(*) AS order_count,
        FIRST(order_date) AS pattern_start,
        LAST(order_date) AS pattern_end,
        SUM(total_amount) AS pattern_revenue
    PATTERN (A B+ C)
    DEFINE
        B AS B.order_date <= PREV(order_date) + 30,
        C AS C.order_date <= PREV(order_date) + 30
);

-- 4.2 Detect Sales Streaks (consecutive days with sales)
SELECT *
FROM (
    SELECT 
        TRUNC(order_date) AS sale_date,
        SUM(total_amount) AS daily_revenue
    FROM sales_orders
    WHERE status IN ('Shipped', 'Delivered')
    GROUP BY TRUNC(order_date)
)
MATCH_RECOGNIZE (
    ORDER BY sale_date
    MEASURES
        FIRST(sale_date) AS streak_start,
        LAST(sale_date) AS streak_end,
        COUNT(*) AS streak_days,
        SUM(daily_revenue) AS streak_revenue
    PATTERN (STREAK+)
    DEFINE
        STREAK AS sale_date = PREV(sale_date) + 1
);

