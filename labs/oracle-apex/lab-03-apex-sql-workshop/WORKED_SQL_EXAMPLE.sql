-- 5.1 Monthly Sales Pivot by Region (for APEX Chart)
SELECT * FROM (
    SELECT 
        TO_CHAR(so.order_date, 'YYYY-MM') AS month,
        sr.region_name,
        so.total_amount
    FROM sales_orders so
    JOIN sales_regions sr ON so.region_id = sr.region_id
    WHERE so.status IN ('Shipped', 'Delivered')
      AND so.order_date >= SYSDATE - 365
)
PIVOT (
    SUM(total_amount) AS revenue,
    COUNT(*) AS order_count
    FOR region_name IN (
        'North America' AS na,
        'Europe' AS eu,
        'Asia Pacific' AS apac,
        'Latin America' AS latam
    )
)
ORDER BY month;

-- 5.2 Product Category Pivot by Quarter
SELECT * FROM (
    SELECT 
        TO_CHAR(so.order_date, 'YYYY') AS year,
        CEIL(TO_NUMBER(TO_CHAR(so.order_date, 'MM')) / 3) AS quarter,
        p.category,
        oi.line_total
    FROM order_items oi
    JOIN sales_orders so ON oi.order_id = so.order_id
    JOIN products p ON oi.product_id = p.product_id
    WHERE so.status IN ('Shipped', 'Delivered')
)
PIVOT (
    SUM(line_total) AS revenue
    FOR category IN ('Electronics' AS electronics, 'Furniture' AS furniture)
)
ORDER BY year, quarter;

-- 5.3 Unpivot for Normalized Data (APEX Collection import)
SELECT customer_id, metric_name, metric_value
FROM (
    SELECT 
        customer_id,
        total_orders,
        total_revenue,
        avg_order_value,
        last_order_date
    FROM customer_summary
)
UNPIVOT (
    metric_value FOR metric_name IN (
        total_orders AS 'Total Orders',
        total_revenue AS 'Total Revenue',
        avg_order_value AS 'Avg Order Value',
        last_order_date AS 'Last Order Date'
    )
);

