-- 3.1 Product Category Hierarchy
WITH category_hierarchy AS (
    SELECT 
        'Electronics' AS cat_name, NULL AS parent_cat, 1 AS sort_order FROM dual UNION ALL
    SELECT 'Laptops', 'Electronics', 1 FROM dual UNION ALL
    SELECT 'Accessories', 'Electronics', 2 FROM dual UNION ALL
    SELECT 'Monitors', 'Electronics', 3 FROM dual UNION ALL
    SELECT 'Furniture', NULL, 2 FROM dual UNION ALL
    SELECT 'Office', 'Furniture', 1 FROM dual
)
SELECT 
    LPAD(' ', (LEVEL - 1) * 3, ' ') || cat_name AS category_tree,
    LEVEL AS depth,
    CONNECT_BY_ISCYCLE AS has_cycle,
    SYS_CONNECT_BY_PATH(cat_name, ' > ') AS full_path
FROM category_hierarchy
START WITH parent_cat IS NULL
CONNECT BY PRIOR cat_name = parent_cat
ORDER SIBLINGS BY sort_order;

-- 3.2 Employee Manager Hierarchy with Sales Performance
SELECT 
    e.emp_name,
    e.job_title,
    m.emp_name AS manager_name,
    COALESCE(s.total_sales, 0) AS direct_sales,
    COALESCE(t.team_sales, 0) AS team_sales,
    LEVEL AS org_level
FROM apex_employees e
LEFT JOIN apex_employees m ON e.manager_id = m.emp_id
LEFT JOIN (
    SELECT sales_rep_id, SUM(total_amount) AS total_sales
    FROM sales_orders
    WHERE status IN ('Shipped', 'Delivered')
    GROUP BY sales_rep_id
) s ON e.emp_id = s.sales_rep_id
LEFT JOIN (
    SELECT mgr.emp_id, SUM(so.total_amount) AS team_sales
    FROM apex_employees emp
    JOIN apex_employees mgr ON emp.manager_id = mgr.emp_id
    JOIN sales_orders so ON emp.emp_id = so.sales_rep_id
    WHERE so.status IN ('Shipped', 'Delivered')
    GROUP BY mgr.emp_id
) t ON e.emp_id = t.emp_id
WHERE e.is_active = 1
START WITH e.manager_id IS NULL
CONNECT BY PRIOR e.emp_id = e.manager_id
ORDER SIBLINGS BY e.emp_name;

