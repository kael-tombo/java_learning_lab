-- 6.1 Generate JSON for APEX REST Data Source
SELECT JSON_OBJECT(
    'order_number' VALUE so.order_number,
    'order_date' VALUE TO_CHAR(so.order_date, 'YYYY-MM-DD"T"HH24:MI:SS'),
    'customer' VALUE JSON_OBJECT(
        'name' VALUE c.customer_name,
        'email' VALUE c.email,
        'tier' VALUE c.tier
    ),
    'items' VALUE (
        SELECT JSON_ARRAYAGG(
            JSON_OBJECT(
                'product' VALUE p.product_name,
                'quantity' VALUE oi.quantity,
                'unit_price' VALUE oi.unit_price,
                'discount_pct' VALUE oi.discount_pct,
                'line_total' VALUE oi.line_total
            )
        )
        FROM order_items oi
        JOIN products p ON oi.product_id = p.product_id
        WHERE oi.order_id = so.order_id
    ),
    'total_amount' VALUE so.total_amount,
    'status' VALUE so.status
) AS order_json
FROM sales_orders so
JOIN customers c ON so.customer_id = c.customer_id
WHERE so.order_id = 1;

