-- 8.2 Materialized View for Dashboard Performance
CREATE MATERIALIZED VIEW mv_monthly_sales_summary
BUILD IMMEDIATE
REFRESH FAST ON COMMIT
ENABLE QUERY REWRITE
AS
SELECT 
    TRUNC(so.order_date, 'MM') AS month,
    sr.region_name,
    p.category,
    COUNT(DISTINCT so.order_id) AS order_count,
    SUM(oi.line_total) AS revenue,
    COUNT(DISTINCT so.customer_id) AS customer_count
FROM sales_orders so
JOIN order_items oi ON so.order_id = oi.order_id
JOIN products p ON oi.product_id = p.product_id
JOIN sales_regions sr ON so.region_id = sr.region_id
WHERE so.status IN ('Shipped', 'Delivered')
GROUP BY TRUNC(so.order_date, 'MM'), sr.region_name, p.category;

