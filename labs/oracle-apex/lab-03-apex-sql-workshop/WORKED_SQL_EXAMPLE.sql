-- 9.1 Cohort Analysis (Customer Retention)
WITH first_orders AS (
    SELECT 
        customer_id,
        MIN(TRUNC(order_date)) AS first_order_month
    FROM sales_orders
    WHERE status IN ('Shipped', 'Delivered')
    GROUP BY customer_id
),
cohort_sizes AS (
    SELECT 
        first_order_month,
        COUNT(*) AS cohort_size
    FROM first_orders
    GROUP BY first_order_month
),
customer_activity AS (
    SELECT 
        fo.customer_id,
        fo.first_order_month,
        TRUNC(so.order_date, 'MM') AS order_month,
        MONTHS_BETWEEN(TRUNC(so.order_date, 'MM'), fo.first_order_month) AS month_number
    FROM first_orders fo
    JOIN sales_orders so ON fo.customer_id = so.customer_id
    WHERE so.status IN ('Shipped', 'Delivered')
)
SELECT 
    cs.first_order_month AS cohort_month,
    cs.cohort_size,
    COUNT(DISTINCT CASE WHEN ca.month_number = 0 THEN ca.customer_id END) AS month_0,
    COUNT(DISTINCT CASE WHEN ca.month_number = 1 THEN ca.customer_id END) AS month_1,
    COUNT(DISTINCT CASE WHEN ca.month_number = 2 THEN ca.customer_id END) AS month_2,
    COUNT(DISTINCT CASE WHEN ca.month_number = 3 THEN ca.customer_id END) AS month_3,
    ROUND(COUNT(DISTINCT CASE WHEN ca.month_number = 1 THEN ca.customer_id END) / cs.cohort_size * 100, 1) AS retention_1m,
    ROUND(COUNT(DISTINCT CASE WHEN ca.month_number = 2 THEN ca.customer_id END) / cs.cohort_size * 100, 1) AS retention_2m,
    ROUND(COUNT(DISTINCT CASE WHEN ca.month_number = 3 THEN ca.customer_id END) / cs.cohort_size * 100, 1) AS retention_3m
FROM cohort_sizes cs
LEFT JOIN customer_activity ca ON cs.first_order_month = ca.first_order_month
GROUP BY cs.first_order_month, cs.cohort_size
ORDER BY cs.first_order_month;

-- 9.2 RFM Analysis (Recency, Frequency, Monetary)
WITH rfm AS (
    SELECT 
        c.customer_id,
        c.customer_name,
        TRUNC(SYSDATE - MAX(so.order_date)) AS recency_days,
        COUNT(DISTINCT so.order_id) AS frequency,
        SUM(so.total_amount) AS monetary
    FROM customers c
    JOIN sales_orders so ON c.customer_id = so.customer_id
    WHERE so.status IN ('Shipped', 'Delivered')
    GROUP BY c.customer_id, c.customer_name
),
rfm_scores AS (
    SELECT 
        *,
        NTILE(5) OVER (ORDER BY recency_days DESC) AS r_score,
        NTILE(5) OVER (ORDER BY frequency) AS f_score,
        NTILE(5) OVER (ORDER BY monetary) AS m_score
    FROM rfm
)
SELECT 
    customer_name,
    recency_days,
    frequency,
    monetary,
    r_score || f_score || m_score AS rfm_score,
    CASE 
        WHEN r_score >= 4 AND f_score >= 4 AND m_score >= 4 THEN 'Champions'
        WHEN r_score >= 3 AND f_score >= 3 AND m_score >= 3 THEN 'Loyal Customers'
        WHEN r_score >= 4 AND f_score <= 2 THEN 'New Customers'
        WHEN r_score <= 2 AND f_score >= 4 THEN 'At Risk'
        WHEN r_score <= 2 AND f_score <= 2 AND m_score <= 2 THEN 'Lost'
        ELSE 'Others'
    END AS segment
FROM rfm_scores
ORDER BY monetary DESC;

