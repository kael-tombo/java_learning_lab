-- 2.1 Running Totals & Moving Averages (for dashboard trends)
SELECT 
    order_date,
    SUM(total_amount) OVER (ORDER BY order_date 
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS running_revenue,
    AVG(total_amount) OVER (ORDER BY order_date 
        ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS moving_avg_7day,
    SUM(total_amount) OVER (ORDER BY order_date 
        ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS moving_sum_30day
FROM (
    SELECT TRUNC(order_date) AS order_date, SUM(total_amount) AS total_amount
    FROM sales_orders
    WHERE order_date >= SYSDATE - 90
    GROUP BY TRUNC(order_date)
)
ORDER BY order_date;

-- 2.2 Top-N Per Group (Top 3 products per category)
SELECT category, product_name, total_sales
FROM (
    SELECT 
        p.category,
        p.product_name,
        SUM(oi.line_total) AS total_sales,
        ROW_NUMBER() OVER (PARTITION BY p.category ORDER BY SUM(oi.line_total) DESC) AS rn
    FROM order_items oi
    JOIN products p ON oi.product_id = p.product_id
    JOIN sales_orders so ON oi.order_id = so.order_id
    WHERE so.status IN ('Shipped', 'Delivered')
      AND so.order_date >= SYSDATE - 365
    GROUP BY p.category, p.product_name
)
WHERE rn <= 3
ORDER BY category, total_sales DESC;

-- 2.3 Percentile Rankings (for customer tier analysis)
SELECT 
    customer_name,
    total_spent,
    PERCENT_RANK() OVER (ORDER BY total_spent) AS percentile_rank,
    NTILE(4) OVER (ORDER BY total_spent) AS quartile,
    CASE NTILE(4) OVER (ORDER BY total_spent)
        WHEN 4 THEN 'Top 25%'
        WHEN 3 THEN '25-50%'
        WHEN 2 THEN '50-75%'
        ELSE 'Bottom 25%'
    END AS spending_tier
FROM (
    SELECT c.customer_name, SUM(so.total_amount) AS total_spent
    FROM sales_orders so
    JOIN customers c ON so.customer_id = c.customer_id
    WHERE so.status IN ('Shipped', 'Delivered')
    GROUP BY c.customer_name
);

-- 2.4 Gap Analysis (Missing dates in sequence)
SELECT 
    TRUNC(order_date) AS order_date,
    LEAD(TRUNC(order_date)) OVER (ORDER BY TRUNC(order_date)) AS next_order_date,
    LEAD(TRUNC(order_date)) OVER (ORDER BY TRUNC(order_date)) - TRUNC(order_date) - 1 AS gap_days
FROM (
    SELECT DISTINCT TRUNC(order_date) AS order_date FROM sales_orders
)
WHERE LEAD(TRUNC(order_date)) OVER (ORDER BY TRUNC(order_date)) - TRUNC(order_date) > 1
ORDER BY gap_days DESC;

