CREATE TABLE sales_regions (
    region_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_name  VARCHAR2(100) NOT NULL,
    region_code  VARCHAR2(10) UNIQUE NOT NULL,
    manager_id   NUMBER,
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE products (
    product_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR2(200) NOT NULL,
    category     VARCHAR2(100),
    subcategory  VARCHAR2(100),
    unit_price   NUMBER(10,2) NOT NULL,
    cost_price   NUMBER(10,2),
    is_active    NUMBER(1) DEFAULT 1 CHECK (is_active IN (0,1)),
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE customers (
    customer_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR2(200) NOT NULL,
    email         VARCHAR2(255) UNIQUE,
    phone         VARCHAR2(50),
    region_id     NUMBER REFERENCES sales_regions(region_id),
    tier          VARCHAR2(20) DEFAULT 'Standard' CHECK (tier IN ('Standard', 'Gold', 'Platinum')),
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE sales_orders (
    order_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number  VARCHAR2(50) UNIQUE NOT NULL,
    customer_id   NUMBER NOT NULL REFERENCES customers(customer_id),
    order_date    DATE DEFAULT SYSDATE,
    status        VARCHAR2(20) DEFAULT 'Pending' CHECK (status IN ('Pending', 'Shipped', 'Delivered', 'Cancelled', 'Returned')),
    total_amount  NUMBER(12,2) DEFAULT 0,
    sales_rep_id  NUMBER REFERENCES apex_employees(emp_id),
    region_id     NUMBER REFERENCES sales_regions(region_id),
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE order_items (
    item_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      NUMBER NOT NULL REFERENCES sales_orders(order_id),
    product_id    NUMBER NOT NULL REFERENCES products(product_id),
    quantity      NUMBER NOT NULL CHECK (quantity > 0),
    unit_price    NUMBER(10,2) NOT NULL,
    discount_pct  NUMBER(5,2) DEFAULT 0,
    line_total    NUMBER(12,2) GENERATED ALWAYS AS (quantity * unit_price * (1 - discount_pct/100)) VIRTUAL
);

