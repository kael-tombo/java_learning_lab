-- 8.4 Result Cache for Expensive LOV Queries
CREATE OR REPLACE FUNCTION get_product_lov_json RETURN CLOB
RESULT_CACHE RELIES_ON (products)
AS
    v_json CLOB;
BEGIN
    SELECT JSON_ARRAYAGG(
        JSON_OBJECT('d' VALUE product_name, 'r' VALUE product_id)
        ORDER BY product_name
    ) INTO v_json
    FROM products
    WHERE is_active = 1;
    RETURN v_json;
END;
