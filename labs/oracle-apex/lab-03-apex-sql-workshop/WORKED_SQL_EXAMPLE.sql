-- 7.1 Interactive Report with Dynamic Columns (using CASE)
SELECT 
    e.emp_name,
    e.job_title,
    CASE 
        WHEN :P3_SHOW_SALARY = 'Y' THEN TO_CHAR(e.salary, '$999,999')
        ELSE '*****'
    END AS salary_display,
    CASE 
        WHEN :P3_SHOW_EMAIL = 'Y' THEN e.emp_email
        ELSE 'Hidden'
    END AS email_display,
    d.dept_name,
    CASE e.is_active WHEN 1 THEN 'Active' ELSE 'Inactive' END AS status
FROM apex_employees e
JOIN apex_departments d ON e.dept_id = d.dept_id
WHERE e.is_active = 1
ORDER BY e.emp_name;

-- 7.2 Report with Drill-Down Link (APEX Link Column)
SELECT 
    e.emp_id,
    e.emp_name,
    e.job_title,
    d.dept_name,
    'f?p=' || :APP_ID || ':3:' || :APP_SESSION || '::::P3_EMP_ID:' || e.emp_id AS edit_link
FROM apex_employees e
JOIN apex_departments d ON e.dept_id = d.dept_id
WHERE e.is_active = 1;

-- 7.3 Faceted Search Query (APEX 20.2+)
SELECT 
    so.order_id,
    so.order_number,
    so.order_date,
    c.customer_name,
    sr.region_name,
    so.status,
    so.total_amount,
    e.emp_name AS sales_rep
FROM sales_orders so
JOIN customers c ON so.customer_id = c.customer_id
JOIN sales_regions sr ON so.region_id = sr.region_id
LEFT JOIN apex_employees e ON so.sales_rep_id = e.emp_id
WHERE so.order_date >= :P1_DATE_FROM
  AND so.order_date <= :P1_DATE_TO
  AND (:P1_STATUS IS NULL OR so.status = :P1_STATUS)
  AND (:P1_REGION IS NULL OR so.region_id = :P1_REGION)
  AND (:P1_REP IS NULL OR so.sales_rep_id = :P1_REP)
ORDER BY so.order_date DESC;

-- 7.4 Pagination with OFFSET/FETCH (APEX Classic Report)
SELECT *
FROM (
    SELECT 
        so.*,
        c.customer_name,
        ROW_NUMBER() OVER (ORDER BY so.order_date DESC) AS rn
    FROM sales_orders so
    JOIN customers c ON so.customer_id = c.customer_id
    WHERE so.status = 'Delivered'
)
WHERE rn BETWEEN :P1_OFFSET + 1 AND :P1_OFFSET + :P1_PAGE_SIZE;

