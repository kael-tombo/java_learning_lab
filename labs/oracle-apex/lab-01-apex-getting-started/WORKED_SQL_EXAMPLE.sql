-- 3.1 Basic Employee Report with Department Name (JOIN)
-- Use in APEX: Interactive Report source query
SELECT 
    e.emp_id,
    e.emp_name,
    e.emp_email,
    e.job_title,
    TO_CHAR(e.hire_date, 'YYYY-MM-DD') AS hire_date,
    e.salary,
    d.dept_name,
    d.dept_location,
    CASE e.is_active WHEN 1 THEN 'Active' ELSE 'Inactive' END AS status
FROM apex_employees e
JOIN apex_departments d ON e.dept_id = d.dept_id
WHERE e.is_active = 1
ORDER BY d.dept_name, e.emp_name;

-- 3.2 Employee Report with Bind Variable for Department Filter
-- Use in APEX: Page item P1_DEPT_ID drives this query
-- In APEX: SELECT ... WHERE e.dept_id = :P1_DEPT_ID OR :P1_DEPT_ID IS NULL
SELECT 
    e.emp_id,
    e.emp_name,
    e.job_title,
    e.salary,
    d.dept_name
FROM apex_employees e
JOIN apex_departments d ON e.dept_id = d.dept_id
WHERE e.is_active = 1
  AND (e.dept_id = :P1_DEPT_ID OR :P1_DEPT_ID IS NULL)
ORDER BY e.emp_name;

-- 3.3 Department Salary Summary (for Chart/ Dashboard)
SELECT 
    d.dept_name,
    COUNT(e.emp_id) AS employee_count,
    ROUND(AVG(e.salary), 2) AS avg_salary,
    MIN(e.salary) AS min_salary,
    MAX(e.salary) AS max_salary,
    SUM(e.salary) AS total_payroll
FROM apex_departments d
LEFT JOIN apex_employees e ON d.dept_id = e.dept_id AND e.is_active = 1
GROUP BY d.dept_name
ORDER BY avg_salary DESC NULLS LAST;

-- -----------------------------------------------------------------------------
-- SECTION 4: APEX List of Values (LOV) Queries
-- -----------------------------------------------------------------------------

-- 4.1 Department LOV for Select Lists
-- Return: dept_name (display), dept_id (return)
SELECT dept_name AS display_value, dept_id AS return_value
FROM apex_departments
ORDER BY dept_name;

-- 4.2 Manager LOV (self-referencing) with hierarchy indicator
SELECT 
    LPAD(' ', (LEVEL - 1) * 2, ' ') || emp_name AS display_value,
    emp_id AS return_value
FROM apex_employees
WHERE is_active = 1
START WITH manager_id IS NULL
CONNECT BY PRIOR emp_id = manager_id
ORDER SIBLINGS BY emp_name;

