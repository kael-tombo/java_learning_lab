-- 6.1 Pagination Query (for Classic Report with Pagination)
-- APEX handles pagination automatically, but understanding the pattern:
SELECT *
FROM (
    SELECT 
        e.*,
        d.dept_name,
        ROW_NUMBER() OVER (ORDER BY e.emp_name) AS rn
    FROM apex_employees e
    JOIN apex_departments d ON e.dept_id = d.dept_id
    WHERE e.is_active = 1
)
WHERE rn BETWEEN :P1_ROW_FROM AND :P1_ROW_TO;

-- 6.2 Search Query with Multiple Optional Filters (APEX best practice)
SELECT 
    e.emp_id,
    e.emp_name,
    e.emp_email,
    e.job_title,
    e.salary,
    d.dept_name,
    m.emp_name AS manager_name
FROM apex_employees e
JOIN apex_departments d ON e.dept_id = d.dept_id
LEFT JOIN apex_employees m ON e.manager_id = m.emp_id
WHERE e.is_active = 1
  AND (:P1_SEARCH IS NULL OR UPPER(e.emp_name) LIKE '%' || UPPER(:P1_SEARCH) || '%')
  AND (:P1_DEPT_ID IS NULL OR e.dept_id = :P1_DEPT_ID)
  AND (:P1_JOB_TITLE IS NULL OR e.job_title = :P1_JOB_TITLE)
  AND (:P1_MIN_SALARY IS NULL OR e.salary >= :P1_MIN_SALARY)
  AND (:P1_MAX_SALARY IS NULL OR e.salary <= :P1_MAX_SALARY)
ORDER BY e.emp_name;

-- 6.3 Hierarchical Report: Organization Chart (using CONNECT BY)
SELECT 
    LEVEL AS lvl,
    LPAD(' ', (LEVEL - 1) * 4, ' ') || emp_name AS org_chart,
    emp_id,
    job_title,
    dept_id,
    salary,
    CONNECT_BY_ISCYCLE AS has_cycle,
    SYS_CONNECT_BY_PATH(emp_name, ' > ') AS path_from_root
FROM apex_employees
WHERE is_active = 1
START WITH manager_id IS NULL
CONNECT BY NOCYCLE PRIOR emp_id = manager_id
ORDER SIBLINGS BY emp_name;

